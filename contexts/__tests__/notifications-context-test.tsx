import React from 'react';
import {act,renderHook} from '@testing-library/react-native';
import AsyncStorage from '@react-native-async-storage/async-storage';
import {NotificationsProvider,useReminders} from '../notifications-context';
import * as native from '@/services/notifications/native';
import {DEFAULT_REMINDERS} from '@/services/notifications/planner';
jest.mock('expo-router',()=>({router:{push:jest.fn()},useRootNavigationState:()=>({key:'root'})}));
jest.mock('../language-context',()=>({useLanguage:()=>({locale:'en'})}));
const mockStudents:any[]=[],mockBanners:any[]=[],mockEntries={},mockIds:number[]=[];
const mockDisplayName=(s:any)=>s.Name;
let mockBannerStatus='loading';
jest.mock('../gamedata-context',()=>({useGameData:()=>({students:mockStudents,displayName:mockDisplayName,ready:true})}));
jest.mock('../banners-context',()=>({useBanners:()=>({banners:mockBanners,status:mockBannerStatus})}));
const mockAp={ready:true,state:null,fullAt:()=>null};
jest.mock('../user-data-context',()=>({useWatchlist:()=>({ids:mockIds,ready:true}),useRoster:()=>({entries:mockEntries,ready:true}),useAp:()=>mockAp}));
jest.mock('@/services/notifications/native',()=>({supported:true,permission:jest.fn(async()=>'granted'),requestPermission:jest.fn(async()=>'granted'),reconcile:jest.fn(async()=>({scheduled:0,errors:0})),listen:jest.fn(()=>()=>{})}));
const wrapper=({children}:{children:React.ReactNode})=><NotificationsProvider>{children}</NotificationsProvider>;
beforeEach(()=>{jest.clearAllMocks();mockBannerStatus='loading';(AsyncStorage.getItem as jest.Mock).mockResolvedValue(null);(AsyncStorage.setItem as jest.Mock).mockResolvedValue(undefined);(native.permission as jest.Mock).mockResolvedValue('granted');});
test('a failed settings read cannot cancel reminders or overwrite preferences; Retry hydrates safely',async()=>{
 (AsyncStorage.getItem as jest.Mock).mockRejectedValueOnce(new Error('storage unavailable'));
 const {result}=renderHook(()=>useReminders(),{wrapper});
 await act(async()=>{});
 expect(result.current.ready).toBe(false);expect(result.current.error).toBe(true);
 expect(native.reconcile).not.toHaveBeenCalled();
 await act(async()=>{await result.current.setPreference('dailyReset',true);});
 expect(AsyncStorage.setItem).not.toHaveBeenCalled();
 (AsyncStorage.getItem as jest.Mock).mockResolvedValue(JSON.stringify({asked:true,preferences:{...DEFAULT_REMINDERS,dailyReset:true}}));
 await act(async()=>{await result.current.refresh();});
 expect(result.current.ready).toBe(true);expect(result.current.preferences.dailyReset).toBe(true);
 expect(native.reconcile).toHaveBeenCalled();
});
test('loading/error banner schedules preserve enabled banner requests, while disabling cancels',async()=>{
 (AsyncStorage.getItem as jest.Mock).mockResolvedValue(JSON.stringify({preferences:{...DEFAULT_REMINDERS,bannerStart:true}}));
 const {result,rerender}=renderHook(()=>useReminders(),{wrapper});await act(async()=>{});
 expect(native.reconcile).toHaveBeenLastCalledWith([],'en',['bannerStart']);
 mockBannerStatus='error';rerender({});await act(async()=>{});
 expect(native.reconcile).toHaveBeenLastCalledWith([],'en',['bannerStart']);
 await act(async()=>{await result.current.setPreference('bannerStart',false);});
 expect(native.reconcile).toHaveBeenLastCalledWith([],'en',[]);
});
test('launch never asks permission; first explicit enable asks once and persists the decision',async()=>{
 (native.permission as jest.Mock).mockResolvedValue('undetermined');
 const {result}=renderHook(()=>useReminders(),{wrapper});await act(async()=>{});
 expect(native.requestPermission).not.toHaveBeenCalled();
 await act(async()=>{await result.current.setPreference('dailyReset',true);});
 expect(native.requestPermission).toHaveBeenCalledTimes(1);
 expect(AsyncStorage.setItem).toHaveBeenCalledWith('reminders:v1',expect.stringContaining('"asked":true'));
 await act(async()=>{await result.current.setPreference('birthdays',true);});
 expect(native.requestPermission).toHaveBeenCalledTimes(1);
});
